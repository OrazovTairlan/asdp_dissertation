MODELFILE_PARAMETERS = {
    "temperature": 0,
    "top_k": 1,
    "top_p": 1,
    "seed": 42,
    "repeat_penalty": 1,
    "num_ctx": 16384,
    "num_predict": 4096,
}

MODELFILE_PATH = Path(__file__).resolve().parent.parent / "modelfiles" / "gpt-oss-kpi.Modelfile"


def modelfile_text(base: str = "gpt-oss:20b") -> str:
    assert '"""' not in MODELFILE_SYSTEM
    params = "\n".join(f"PARAMETER {k} {v}" for k, v in MODELFILE_PARAMETERS.items())
    return f'FROM {base}\nSYSTEM """\n{MODELFILE_SYSTEM}\n"""\n{params}\n'


def all_prompts() -> dict[str, str]:
    return {
        "ground_rules": GROUND_RULES,
        "extract": EXTRACT_SYSTEM,
        "classify": CLASSIFY_SYSTEM,
        "metric": METRIC_SYSTEM,
        "link_images": LINK_SYSTEM,
        "position": POSITION_SYSTEM,
        "vision": VISION_SYSTEM,
        "interactive_modelfile": MODELFILE_SYSTEM,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description="Служебные команды промптов")
    ap.add_argument("--write-modelfile", action="store_true", help=f"записать {MODELFILE_PATH.name}")
    ap.add_argument("--print", action="store_true", help="вывести Modelfile")
    args = ap.parse_args()
    text = modelfile_text()
    if args.write_modelfile:
        MODELFILE_PATH.parent.mkdir(parents=True, exist_ok=True)
        MODELFILE_PATH.write_text(text, encoding="utf-8", newline="\n")
        print(f"записано: {MODELFILE_PATH}")
    if args.print or not args.write_modelfile:
        print(text)


if __name__ == "__main__":
    main()
